def load_img_steering(datadir, df):
  """
  This function appends the name of the containing folder to the image name. 
  For each row of the data frame it adds the images of the columns "center", 
  "right", "left" to the list of images and associates them with the steering angle
  of the column "steering". The steering angle is modified according to the 
  camera that took the image. 
  input: 
    datadir: path to the containing folder
    df: Dataframe with all the name of each image and its related steering angle
  output: 
    array with the image names and theis steering angle 
  """

  image_path = []
  steering = []

  for i in range(len(df)):
      ##indexed_data = df_udacity.iloc[i]
      indexed_data = df.iloc[i]
      center, left, right = indexed_data[0], indexed_data[1], indexed_data[2]
      image_path.append(os.path.join(datadir, center.strip()))
      steering.append(float(indexed_data[3]))
      image_path.append(os.path.join(datadir, left.strip()))
      if abs(float(indexed_data[3])) > 1:
          steering.append(float(indexed_data[3]) + 0.25)
      else:
          steering.append(float(indexed_data[3]) + 0.18)
      #steering.append(float(indexed_data[3]) + 0.2) # Offset + 0.15
      image_path.append(os.path.join(datadir, right.strip()))
      if abs(float(indexed_data[3])) > 1:
          steering.append(float(indexed_data[3]) - 0.25)
      else:
          steering.append(float(indexed_data[3]) - 0.18)
      #steering.append(float(indexed_data[3]) - 0.2) # Offset - 0.15
  image_paths = np.asarray(image_path)
  steerings = np.asarray(steering)
  return image_paths, steerings

