def normal_load(image_paths, steering_ang, batch_size, istraining):
  """
  This function load the image and the steering angles. 
  If the image is a training image then it will be randmly augmented and preprocess 
  else just preprocess. For training images, not anly the augmented image will 
  be append into the list but also the original one
  This function avoids the bottleneck that occurs when using a generator between 
  the CPU and GPU. The complete data will be stored in RAM.
  """
  while True:
      batch_img = []
      batch_steering = []

      for i in range(batch_size):
          random_index = random.randint(0, len(image_paths) - 1)

          if istraining: 
              if np.random.randint(6) == 0: 
                  im = mpimg.imread(image_paths[random_index]) 
                  steering = steering_ang[random_index] 
                  im = img_preprocess(im) 
                  batch_img.append(im) 
                  batch_steering.append(steering) 
              
              im, steering = random_augment( 
                  image_paths[random_index], steering_ang[random_index]
              )

          else:
              im = mpimg.imread(image_paths[random_index])
              steering = steering_ang[random_index]

          im = img_preprocess(im)
          batch_img.append(im)
          batch_steering.append(steering)
          

      return (np.asarray(batch_img), np.asarray(batch_steering))

