"""## Preprocessing and image augmentation functions"""

def zoom(image):
    """
    This function resizes the image to the new input shape 
    """
    zoom = iaa.Affine(scale=(1, 1.5))
    image = zoom.augment_image(image)
    return image

def random_flip(image, steering_angle):
  """
  This function flipts the image left/right, and adjust the steering angle.
  """
  image = cv2.flip(image, 1)
  steering_angle = -steering_angle
  return image, steering_angle

def pan(image):
  """
  This function shifts the image (vertical shift and horizontal shift) 
  by a small amount. 
  Create “new” pixels in the image without a defined content, e.g. 
  if the image is translated to the left, pixels are created on the right.
  """
  pan = iaa.Affine(translate_percent={"x": (-0.1, 0.1), "y": (-0.1, 0.1)})
  image = pan.augment_image(image)
  return image

def random_brightness(image):
  """
  This function multiply all pixels in an image with a random value sampled once per image.
  This augmenter can be used to make images lighter or darker.
  """
  brightness = iaa.Multiply((0.2, 1.6))
  image = brightness.augment_image(image)
  return image

def image_brighten(image):
  """
  This function adjust brightness of the image.
  """
  # HSV (Hue, Saturation, Value) is also called HSB ('B' for Brightness).
  hsv_image = cv2.cvtColor(image, cv2.COLOR_BGR2HSV)
  default_bias = 0.25
  brightness = default_bias + np.random.uniform() 
  hsv_image[:, :, 2] = hsv_image[:, :, 2] * brightness
  return cv2.cvtColor(hsv_image, cv2.COLOR_HSV2RGB)

def random_shadow(image):
  """
  This function generates and adds random shadow. 
  This function was specially created to simulate the shadows of the second track.
  """
  IMAGE_HEIGHT, IMAGE_WIDTH, IMAGE_CHANNELS = 160, 320, 3
  # (x1, y1) and (x2, y2) forms a line
  # xm, ym gives all the locations of the image
  x1, y1 = IMAGE_WIDTH * np.random.rand(), 0
  x2, y2 = IMAGE_WIDTH * np.random.rand(), IMAGE_HEIGHT
  xm, ym = np.mgrid[0:IMAGE_HEIGHT, 0:IMAGE_WIDTH]

  # mathematically speaking, we want to set 1 below the line and zero otherwise
  # Our coordinate is up side down.  So, the above the line: 
  # (ym-y1)/(xm-x1) > (y2-y1)/(x2-x1)
  # as x2 == x1 causes zero-division problem, we'll write it in the below form:
  # (ym-y1)*(x2-x1) - (y2-y1)*(xm-x1) > 0
  mask = np.zeros_like(image[:, :, 1])
  mask[(ym - y1) * (x2 - x1) - (y2 - y1) * (xm - x1) > 0] = 1

  # choose which side should have shadow and adjust saturation
  cond = mask == np.random.randint(2)
  s_ratio = np.random.uniform(low=0.2, high=0.5)

  # adjust Saturation in HLS(Hue, Light, Saturation)
  hls = cv2.cvtColor(image, cv2.COLOR_RGB2HLS)
  hls[:, :, 1][cond] = hls[:, :, 1][cond] * s_ratio
  return cv2.cvtColor(hls, cv2.COLOR_HLS2RGB)

def random_augment(image, steering_angle):
    """
    This function generates randomly an augumented image and adjust steering angle.
    """
    image = mpimg.imread(image)
    if np.random.rand() < 0.5:
        image = pan(image)
    if np.random.rand() < 0.5:
        image = zoom(image)
    if np.random.rand() < 0.5:
        image = random_brightness(image)
    if np.random.rand() < 0.5:
        image = image_brighten(image)
    if np.random.rand() < 0.5:
        image = random_shadow(image)
    if np.random.rand() < 0.5:
        image, steering_angle = random_flip(image, steering_angle)
    return image, steering_angle

def img_preprocess(img):
  """
  This function preprocess the image. It will be croped, changed the YUV and 
  Gaussian blur values, resized and normalized to prepare it for the CNN model.
  """

  ## Crop image to remove unnecessary features
  img = img[40:140, :, :] #img[60:135, :, :]
  ## Change to YUV image
  img = cv2.cvtColor(img, cv2.COLOR_RGB2YUV)
  ## Apply Gaussian Smoothing on the input source image.
  img = cv2.GaussianBlur(img, (3, 3), 0)
  ## Decrease size for easier processing
  img = cv2.resize(img, (200, 66), cv2.INTER_AREA)
  ## Normalize values
  img = (img - 128.) / 128
  return img

